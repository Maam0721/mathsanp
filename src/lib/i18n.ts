export type TranslationKey = keyof typeof translations.mn;
export type Dictionary = Record<TranslationKey, string>;

export function getTranslations(language: Language): Dictionary {
  return translations[language] as Dictionary;
}

export function getAuthErrorMessage(
  error: { message: string; code?: string },
  language: Language,
) {
  const t = getTranslations(language);
  const details = `${error.code ?? ""} ${error.message}`.toLowerCase();

  if (/email_not_confirmed|email not confirmed/.test(details)) return t.authEmailNotConfirmed;
  if (/weak_password|password.*(weak|short|characters)|password should/.test(details)) return t.authWeakPassword;
  if (/user_already_exists|email_exists|already registered|user already registered/.test(details)) {
    return t.authEmailRegistered;
  }
  if (/invalid_credentials|invalid login credentials|invalid email or password/.test(details)) {
    return t.authInvalidCredentials;
  }
  if (/failed to fetch|networkerror|network request failed|fetch failed|load failed/.test(details)) {
    return t.authNetworkError;
  }
  return t.authError;
}
